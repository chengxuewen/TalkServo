//! D19 instance lifecycle: `init` renders a portable instance directory,
//! start/stop/restart drive the vendored oxmgr supervisor. Render functions
//! are PURE (zero process side effects — sister templates.rs discipline:
//! everything here is deterministically unit-testable).

use std::path::{Path, PathBuf};

/// oxmgr namespace for this deployment unit (status/stop filter anchor).
pub const NAMESPACE: &str = "talkservo";
pub const SERVER_APP: &str = "talkservo-server";
pub const WEB_APP: &str = "talkservo-web";

/// server.yaml template — non-secret config only; secrets live in
/// identity/env 0600 (oxfile env_file). Placeholders rendered by init.
pub fn render_server_yaml(announced_ip: &str, public_base: &str, rtc_min: u16, rtc_max: u16) -> String {
    format!(
        "# talkservo-server instance config (plan-6/D19) — env vars override these (12-factor).\n\
         # Secrets & bind live in identity/env (0600), NOT here (this file may be reviewed/copied).\n\
         announced_ip: {announced_ip}\n\
         public_base: {public_base}\n\
         rtc_port_min: {rtc_min}\n\
         rtc_port_max: {rtc_max}\n\
         heartbeat_s: 30\n\
         no_rtp_watchdog_ms: 2000\n\
         room_idle_ttl_s: 600\n\
         max_peers: 10\n\
         max_queue: 8\n\
         floor_max_hold_ms: 45000\n"
    )
}

/// oxmgr app file (sister-proven schema: version/defaults/apps{command,env,logs}).
/// caddy entry rendered only when a caddy binary was discovered at init time —
/// restart_policy=always against a missing file is a spin storm (sister bF1).
pub fn render_oxfile(
    dir_abs: &Path,
    server_bin: &Path,
    caddy: Option<&Path>,
    server_env: &[(String, String)],
) -> String {
    let dir = dir_abs.to_string_lossy();
    let mut out = format!(
        "# generated by `talkservo-server init` — topology edits: change this file + restart\n\
         version = 1\n\n[defaults]\nnamespace = \"{NAMESPACE}\"\nrestart_policy = \"always\"\ncwd = \"{dir}\"\n"
    );
    out.push_str(&format!(
        "\n[[apps]]\nname = \"{SERVER_APP}\"\ncommand = \"{} run --config {dir}/etc/server.yaml\"\nrestart_policy = \"always\"\n",
        server_bin.to_string_lossy(),
    ));
    // env literals: identity/env secrets + bind are rendered IN (oxmgr-spawned
    // processes don't inherit the invoking CLI env — sister C33 lesson)
    if !server_env.is_empty() {
        out.push_str("[apps.env]\n");
        out.push_str(&format!("TS_CONFIG_FILE = \"{dir}/etc/server.yaml\"\n"));
        for (k, v) in server_env {
            out.push_str(&format!("{k} = \"{v}\"\n"));
        }
    }
    out.push_str(&format!(
        "[apps.logs]\nstdout = \"{dir}/run/logs/{SERVER_APP}.out.log\"\nstderr = \"{dir}/run/logs/{SERVER_APP}.err.log\"\n"
    ));
    if let Some(caddy) = caddy {
        out.push_str(&format!(
            "\n[[apps]]\nname = \"{WEB_APP}\"\ncommand = \"{} run --config {dir}/etc/Caddyfile --adapter caddyfile\"\nrestart_policy = \"always\"\n\
             [apps.logs]\nstdout = \"{dir}/run/logs/{WEB_APP}.out.log\"\nstderr = \"{dir}/run/logs/{WEB_APP}.err.log\"\n",
            caddy.to_string_lossy(),
        ));
    }
    out
}

/// 48-byte base64 secret from /dev/urandom (same shape as
/// `openssl rand -base64 48`); degraded entropy falls back loudly, never silently.
fn gen_secret() -> String {
    use base64::Engine as _;
    use std::io::Read as _;
    let mut raw = [0u8; 48];
    if let Ok(mut f) = std::fs::File::open("/dev/urandom") {
        let _ = f.read_exact(&mut raw);
    } else {
        tracing::warn!(
            event = "secret_entropy_fallback",
            "urandom unavailable — time/pid mix; REPLACE secrets before production"
        );
        let mut seed = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map(|d| d.as_nanos() as u64)
            .unwrap_or(0)
            ^ (u64::from(std::process::id()) << 32);
        for b in raw.iter_mut() {
            seed = seed
                .wrapping_mul(0x9E37_79B9_7F4A_7C15)
                .rotate_left(17);
            *b = (seed >> 40) as u8;
        }
    }
    base64::engine::general_purpose::STANDARD.encode(raw)
}

/// Build/refresh an instance directory. Idempotent: EXISTING secrets/Caddyfile
/// are preserved (re-init after deploy must not rotate credentials — sister
/// entrypoint bootstrap semantics). Fresh: 0600 identity/env with generated
/// TS_JWT_SECRET/TS_ADMIN_SECRET (+ empty TURN_SECRET slot for the operator).
pub fn init_instance(dir: &Path, server_bin: &Path) -> std::io::Result<Vec<String>> {
    let abs = dir.canonicalize().unwrap_or_else(|_| dir.to_path_buf());
    let mut log = Vec::new();
    std::fs::create_dir_all(abs.join("etc"))?;
    std::fs::create_dir_all(abs.join("run/logs"))?;
    std::fs::create_dir_all(abs.join("identity"))?;

    let envf = abs.join("identity/env");
    if !envf.exists() {
        let body = format!(
            "TS_JWT_SECRET={}\nTS_ADMIN_SECRET={}\nTS_BIND=0.0.0.0:8080\nTURN_SECRET=\n",
            gen_secret(),
            gen_secret(),
        );
        std::fs::write(&envf, body)?;
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            std::fs::set_permissions(&envf, std::fs::Permissions::from_mode(0o600))?;
        }
        log.push("identity/env created (0600, secrets generated)".into());
    } else {
        log.push("identity/env preserved (existing secrets)".into());
    }

    let yaml = abs.join("etc/server.yaml");
    if !yaml.exists() {
        std::fs::write(&yaml, render_server_yaml("127.0.0.1", "http://127.0.0.1:8080", 40000, 40100))?;
        log.push("etc/server.yaml created (edit announced_ip/public_base for LAN)".into());
    } else {
        log.push("etc/server.yaml preserved".into());
    }

    let caddyfile = abs.join("etc/Caddyfile");
    let caddy = which("caddy").or_else(|| {
        let in_bin = abs.join("bin/caddy");
        in_bin.is_file().then_some(in_bin)
    });
    if caddy.is_some() && !caddyfile.exists() {
        std::fs::write(
            &caddyfile,
            "# talkservo LAN self-signed scaffold (plan-6): regenerate per deploy/Caddyfile\n\
             # openssl req recipe in docs/modules/06; enable block once certs exist:\n\
             # https://:8443 {\n#     tls etc/lan-cert.pem etc/lan-key.pem\n#     reverse_proxy 127.0.0.1:8080\n# }\n",
        )?;
        log.push("etc/Caddyfile scaffolded (caddy found; enable block after certs)".into());
    }

    let oxfile = abs.join("run/oxfile.toml");
    if !oxfile.exists() {
        let env_pairs: Vec<(String, String)> = std::fs::read_to_string(&envf)
            .unwrap_or_default()
            .lines()
            .filter_map(|l| l.split_once('='))
            .map(|(k, v)| (k.to_string(), v.to_string()))
            .collect();
        std::fs::write(&oxfile, render_oxfile(&abs, server_bin, caddy.as_deref(), &env_pairs))?;
        log.push("run/oxfile.toml created".into());
    } else {
        log.push("run/oxfile.toml preserved (edit to change topology)".into());
    }
    Ok(log)
}

/// resolve oxmgr: instance bin/ first (deployed package), then PATH.
pub fn discover_oxmgr(dir: &Path) -> Option<PathBuf> {
    let in_dir = dir.join("bin/oxmgr");
    if in_dir.is_file() {
        return Some(in_dir);
    }
    which("oxmgr")
}

fn which(bin: &str) -> Option<PathBuf> {
    std::env::var("PATH")
        .ok()?
        .split(std::path::MAIN_SEPARATOR)
        .find_map(|p| {
            let cand = PathBuf::from(p).join(bin);
            cand.is_file().then_some(cand)
        })
}

/// parse app names out of a rendered oxfile (stop/restart cluster targets).
pub fn oxfile_apps(oxfile_text: &str) -> Vec<String> {
    oxfile_text
        .lines()
        .filter_map(|l| l.trim().strip_prefix("name = ").and_then(|v| v.trim().trim_matches('"').to_string().into()))
        .collect()
}

/// stop then delete every app declared by the instance oxfile (sister
/// shape: cluster teardown = stop+delete per app; individual misses —
/// already-down app — don't abort the sweep).
pub fn oxmgr_stop_cluster(dir: &Path) -> i32 {
    let Some(ox) = discover_oxmgr(dir) else {
        eprintln!("oxmgr not found (instance bin/ or PATH) — deploy package includes it (plan-6 T2)");
        return 2;
    };
    let names = std::fs::read_to_string(dir.join("run/oxfile.toml"))
        .map(|t| oxfile_apps(&t))
        .unwrap_or_default();
    if names.is_empty() {
        eprintln!("no apps found in run/oxfile.toml — run `talkservo-server init <dir>` first");
        return 2;
    }
    let mut worst = 0;
    for n in &names {
        let a = [std::ffi::OsStr::new("stop"), std::ffi::OsStr::new(n)];
        worst = worst.max(run_ox(&ox, &a));
        let d = [std::ffi::OsStr::new("delete"), std::ffi::OsStr::new(n)];
        run_ox(&ox, &d);
    }
    worst
}

fn run_ox(ox: &Path, args: &[&std::ffi::OsStr]) -> i32 {
    let owned: Vec<std::ffi::OsString> = args.iter().map(|s| s.to_os_string()).collect();
    match std::process::Command::new(ox).args(&owned).status() {
        Ok(s) => s.code().unwrap_or(1),
        Err(e) => {
            eprintln!("oxmgr spawn failed: {e}");
            1
        }
    }
}

/// forward an oxmgr verb against the instance oxfile. Returns process exit code.
pub fn oxmgr_forward(dir: &Path, args: &[&str]) -> i32 {
    let Some(ox) = discover_oxmgr(dir) else {
        eprintln!("oxmgr not found (instance bin/ or PATH) — deploy package includes it (plan-6 T2)");
        return 2;
    };
    let oxfile = dir.join("run/oxfile.toml");
    if args.first().is_some_and(|a| *a == "apply") && !oxfile.exists() {
        eprintln!("missing {} — run `talkservo-server init <dir>` first", oxfile.display());
        return 2;
    }
    let mut cmd = std::process::Command::new(ox);
    cmd.args(args);
    if args.contains(&"apply") {
        cmd.arg(&oxfile);
    }
    match cmd.status() {
        Ok(s) => s.code().unwrap_or(1),
        Err(e) => {
            eprintln!("oxmgr spawn failed: {e}");
            1
        }
    }
}

/// Effective TS_BIND of an instance: the oxfile literal is what actually
/// runs (init renders identity/env INTO it — editing identity alone does
/// not move the running process; sister C33 literal-render tradeoff).
pub fn instance_bind(dir: &Path) -> String {
    for cand in [dir.join("run/oxfile.toml"), dir.join("identity/env")] {
        if let Ok(t) = std::fs::read_to_string(&cand) {
            for line in t.lines() {
                let l = line.trim();
                // oxfile: TS_BIND = "x"  |  identity: TS_BIND=x
                if let Some(v) = l.strip_prefix("TS_BIND = \"").and_then(|v| v.strip_suffix('\u{22}')) {
                    return v.to_string();
                }
                if let Some(v) = l.strip_prefix("TS_BIND=") {
                    if !v.is_empty() {
                        return v.to_string();
                    }
                }
            }
        }
    }
    "127.0.0.1:8080".into()
}

/// healthz probe for `status` (no HTTP client dep: raw TCP GET, HTTP/1.0).
pub fn probe_healthz(bind: &str, timeout: std::time::Duration) -> bool {
    let host_port = bind.rsplit_once("://").map(|(_, r)| r).unwrap_or(bind);
    let Some((host, port)) = host_port.rsplit_once(':') else { return false };
    // numeric binds only (instance templates use IPs); 0.0.0.0 probes via loopback
    let host = if host == "0.0.0.0" || host == "::" { "127.0.0.1" } else { host };
    let Ok(ip) = host.parse::<std::net::IpAddr>() else { return false };
    let Ok(p) = port.parse::<u16>() else { return false };
    let addr = std::net::SocketAddr::new(ip, p);
    let deadline = std::time::Instant::now() + timeout;
    loop {
        let stream = std::net::TcpStream::connect_timeout(&addr, timeout);
        if let Ok(mut s) = stream {
            use std::io::{Read as _, Write as _};
            let _ = s.write_all(b"GET /healthz HTTP/1.0\r\n\r\n");
            let mut buf = [0u8; 64];
            if let Ok(n) = s.read(&mut buf) {
                let head = String::from_utf8_lossy(&buf[..n]);
                if head.contains("200") {
                    return true;
                }
            }
        }
        if std::time::Instant::now() > deadline {
            return false;
        }
        std::thread::sleep(std::time::Duration::from_millis(100));
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn oxfile_shape() {
        let env = vec![];
        let t = render_oxfile(Path::new("/opt/ts"), Path::new("/opt/ts/bin/talkservo-server"), None, &env);
        assert!(t.contains("namespace = \"talkservo\""));
        assert!(t.contains("run --config /opt/ts/etc/server.yaml"));
        assert!(!t.contains(WEB_APP), "no caddy entry when undiscovered");
        let t2 = render_oxfile(Path::new("/opt/ts"), Path::new("/opt/ts/bin/talkservo-server"), Some(Path::new("/usr/bin/caddy")), &env);
        assert!(t2.contains(WEB_APP));
    }

    #[test]
    fn init_is_idempotent_and_holds_secrets() {
        let dir = std::env::temp_dir().join(format!("ts-init-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        let first = init_instance(&dir, Path::new("/bin/talkservo-server")).unwrap();
        assert!(first.iter().any(|l| l.contains("created (0600")));
        let secrets = std::fs::read_to_string(dir.canonicalize().unwrap().join("identity/env")).unwrap();
        assert!(secrets.contains("TS_JWT_SECRET=") && secrets.contains("TS_ADMIN_SECRET="));
        let jwt_line: Vec<&str> = secrets.lines().filter(|l| l.starts_with("TS_JWT_SECRET=")).collect();
        assert!(jwt_line[0].len() > 40, "secret generated");
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mode = std::fs::metadata(dir.join("identity/env")).unwrap().permissions().mode();
            assert_eq!(mode & 0o777, 0o600);
        }
        let second = init_instance(&dir, Path::new("/bin/talkservo-server")).unwrap();
        assert!(second.iter().any(|l| l.contains("preserved (existing secrets")));
        let again = std::fs::read_to_string(dir.join("identity/env")).unwrap();
        assert_eq!(secrets, again, "re-init must NOT rotate credentials");
    }

    #[test]
    fn yaml_roundtrips_through_loader() {
        // shared with config tests: env is process-global
        let _g = crate::config::ENV_LOCK
            .lock()
            .unwrap_or_else(|e| e.into_inner());
        crate::config::clear_config_env();
        // instance reality: identity/env (rendered into oxfile apps.env) is
        // where secrets come from — server.yaml deliberately carries none
        unsafe { std::env::set_var("TS_JWT_SECRET", "instance-test-x") };
        let dir = std::env::temp_dir().join(format!("ts-yaml-{}", std::process::id()));
        std::fs::create_dir_all(dir.join("etc")).unwrap();
        std::fs::write(dir.join("etc/server.yaml"), render_server_yaml("192.168.1.9", "https://192.168.1.9:8443", 40960, 41215)).unwrap();
        let c = crate::config::Config::load_yaml(&dir.join("etc/server.yaml")).expect("generated yaml loads");
        assert_eq!(c.rtc_port_min, 40960);
        assert_eq!(c.public_base.as_deref(), Some("https://192.168.1.9:8443"));
        unsafe { std::env::remove_var("TS_JWT_SECRET") };
    }

    #[test]
    fn missing_oxmgr_exits_two() {
        let _g = crate::config::ENV_LOCK
            .lock()
            .unwrap_or_else(|e| e.into_inner());
        let dir = std::env::temp_dir().join(format!("ts-noox-{}", std::process::id()));
        let _ = std::fs::create_dir_all(&dir);
        // PATH stripped → deterministic miss
        let saved = std::env::var_os("PATH");
        unsafe { std::env::set_var("PATH", &dir) };
        let code = oxmgr_forward(&dir, &["apply"]);
        unsafe {
            match saved {
                Some(p) => std::env::set_var("PATH", p),
                None => std::env::remove_var("PATH"),
            }
        }
        assert_eq!(code, 2);
    }
}
